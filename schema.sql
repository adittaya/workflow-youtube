-- ─── Run heartbeats (proves a run is alive; used to steal dead-owner locks) ─
CREATE TABLE IF NOT EXISTS public.run_heartbeats (
    project_id  text PRIMARY KEY,
    run_id      text NOT NULL DEFAULT '',                    -- same value as run_locks.owner
    iteration   bigint NOT NULL DEFAULT 0,
    status      text NOT NULL DEFAULT 'running',             -- running | done | crashed
    message     text NOT NULL DEFAULT '',
    last_seen   timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
