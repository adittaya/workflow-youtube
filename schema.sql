    github_repo         text NOT NULL DEFAULT '',
    channels            text NOT NULL DEFAULT '',            -- CSV of @handles/IDs
    shortlink_provider  text NOT NULL DEFAULT 'vplink',
    shortlink_api_key   text NOT NULL DEFAULT '',
    warmup_days         integer NOT NULL DEFAULT 0,
    warmup_start        text NOT NULL DEFAULT '',
    comment_moderation  text NOT NULL DEFAULT 'heldForReview',
    mirror_title_prefix text NOT NULL DEFAULT '',
    deployed_at         text,
    uploads_per_day     integer NOT NULL DEFAULT 2,
    initial_backfill    integer NOT NULL DEFAULT 5,
    upload_schedule     text NOT NULL DEFAULT '',
