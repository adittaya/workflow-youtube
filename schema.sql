    account_id          text NOT NULL DEFAULT '',   -- linked accounts.name (upload identity)
    shortlink_provider  text NOT NULL DEFAULT 'vplink',
    shortlink_api_key   text NOT NULL DEFAULT '',
    comment_moderation  text NOT NULL DEFAULT 'heldForReview',
    mirror_title_prefix text NOT NULL DEFAULT '',
    mirror_description_suffix text NOT NULL DEFAULT '',
    custom_title        text NOT NULL DEFAULT '',
    custom_description  text NOT NULL DEFAULT '',
    custom_comment      text NOT NULL DEFAULT '',
    privacy_status      text NOT NULL DEFAULT 'public',
    category_id         text NOT NULL DEFAULT '22',
    enabled             boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

