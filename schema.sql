-- =============================================================================
-- YT VIDEO AUTOMATION — Comprehensive Supabase Schema
-- =============================================================================
-- Single source of truth for the manual upload tool. Every table below is
-- created if it does not already exist; new columns are added when missing;
-- indexes and the helper views are created/replaced idempotently. Safe to run
-- repeatedly.
--
-- RUN: open the Supabase Dashboard SQL Editor for this project and paste the
--      whole file, or run it through the `supabase` CLI / psql. The tool's
--      service key bypasses RLS; the permissive policies below additionally
--      allow the anon role to read state (used by status dashboards).
--
-- 24/7 automation is GONE: the old 24/7 tables (channels, channel_cursors,
-- mirror_state, mirror_stats, work_queue, run_locks, run_heartbeats) and the
-- github/channel/warmup/schedule/proxy project columns are dropped below.
-- =============================================================================

