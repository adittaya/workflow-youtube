-- ─── Row Level Security: open access (bot uses service key which bypasses
--     RLS anyway; these policies additionally permit anon/dashboard reads) ─
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'projects','settings','accounts','channels','channel_cursors',
        'upload_state','upload_logs','mirror_state','mirror_stats',
        'work_queue','run_locks','run_heartbeats','verify_checks','alerts'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t);
        EXECUTE format('DROP POLICY IF EXISTS "allow_all_%I" ON public.%I;', t, t);
        EXECUTE format(
            'CREATE POLICY "allow_all_%I" ON public.%I FOR ALL USING (true) WITH CHECK (true);',
            t, t);
    END LOOP;
END $$;

-- ─── Helper view: one row per project with live operational status ────────
CREATE OR REPLACE VIEW public.v_project_status AS
SELECT
    p.id                              AS project_id,
    p.name                            AS project_name,
    p.github_repo                     AS repo,
    p.enabled                         AS enabled,
    p.channels                        AS channels,
    p.uploads_per_day                 AS uploads_per_day,
    p.warmup_days                     AS warmup_days,
    us.total_uploaded                 AS total_uploaded,
    us.last_upload_date               AS last_upload_date,
    CASE WHEN jsonb_typeof(us.processed_hashes) = 'array'
         THEN jsonb_array_length(us.processed_hashes) ELSE 0 END AS processed_count,
    (SELECT count(*)::int FROM public.upload_logs l
      WHERE l.project_id = p.id::text)              AS log_count,
    (SELECT count(*)::int FROM public.upload_logs l
      WHERE l.project_id = p.id::text
        AND l.upload_date = to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD'))
                                                     AS today_uploaded,
    (SELECT count(*)::int FROM public.work_queue w
      WHERE w.project_id = p.id::text AND w.status = 'pending')
                                                     AS queued_pending,
    (SELECT count(*)::int FROM public.work_queue w
      WHERE w.project_id = p.id::text AND w.status = 'in_progress')
                                                     AS processing,
    rl.owner                          AS lock_owner,
    rl.expires_at                     AS lock_expires_at,
    hb.run_id                         AS heartbeat_run,
    hb.last_seen                      AS heartbeat_last_seen,
    hb.iteration                      AS heartbeat_iteration,
    p.updated_at                      AS config_updated_at
FROM public.projects p
LEFT JOIN public.upload_state  us ON us.project_id = p.id::text
LEFT JOIN public.run_locks     rl ON rl.project_id = p.id::text
LEFT JOIN public.run_heartbeats hb ON hb.project_id = p.id::text;

-- ─── Helper view: latest verify-check result per project/check ─────────────
CREATE OR REPLACE VIEW public.v_verify_health AS
SELECT
    v.project_id,
    p.name AS project_name,
    count(*) FILTER (WHERE v.status = 'fail')  AS fails,
    count(*) FILTER (WHERE v.status = 'warn')  AS warns,
    count(*) FILTER (WHERE v.status = 'ok')    AS oks,
    max(v.checked_at)                          AS last_checked,
    -- worst status per project ('fail' > 'warn' > 'ok')
    coalesce(
        min(CASE v.status WHEN 'fail' THEN 2 WHEN 'warn' THEN 1 ELSE 0 END),
        0
    )                                          AS worst
FROM public.verify_checks v
LEFT JOIN public.projects p ON p.id::text = v.project_id
GROUP BY v.project_id, p.name;

-- ─── Helper view: unresolved alerts ────────────────────────────────────────
CREATE OR REPLACE VIEW public.v_open_alerts AS
SELECT a.*
FROM public.alerts a
WHERE a.resolved_at IS NULL
ORDER BY a.created_at DESC;
